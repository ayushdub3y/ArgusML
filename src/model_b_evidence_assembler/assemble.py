"""Implements §5 and §12: Model B Evidence Assembler with deterministic fact-validation.

ARCHITECTURE.md references:
- §3 (Deterministic vs. ML vs. LLM boundary: Model B never decides accept/contest/escalate;
  it only drafts human-readable prose within the contest path chosen upstream by decision_engine.py).
- §5 (Modeling: Model B Evidence Assembler — JSON-schema-constrained output populating
  Razorpay's real contest payload: summary + typed evidence like shipping_proof).
- §12 (Defense-only statement: Aegis never fabricates evidence. The fact-validation layer
  blocks any LLM-drafted field that doesn't match the source record rather than silently dropping it).
- §13 (Explicit guardrails against scope creep: Sandbox/test-mode only, graceful degradation).

========================================================================================
MODEL B JSON-SCHEMA CONTRACT & DESIGN SPECIFICATION (§4, §5)
========================================================================================
Model B produces a contest payload strictly conforming to Razorpay's PATCH /v1/disputes/{id}/contest
schema, matching the exact shape produced by razorpay_client.build_contest_payload_from_evidence:

{
  "summary": string,  // <-- ONLY FIELD GENERATED BY LLM (human-readable factual narrative)
  "shipping_proof": { // <-- STRUCTURED FIELDS INJECTED VERBATIM FROM EVIDENCE IN CODE
    "order_id": string,
    "dispatch_ts": integer | null,
    "delivery_ts": integer | null,
    "delivery_otp_confirmed": boolean,
    "pod_document_id": string (optional),
    "delivery_geotag": [float, float] (optional)
  },
  // OR for digital voucher fulfillment:
  "digital_delivery": {
    "order_id": string,
    "redemption_ts": integer | null,
    "fulfillment_type": "digital_voucher"
  }
}

BOUNDARY SPECIFICATION:
1. LLM-Generated Prose (Model B prompt):
   - Only `summary`: A concise, human-readable narrative summarizing the fulfillment facts.
   - Constrained by prompt_template.txt to output ONLY JSON {"summary": "..."}.
2. Structured Values Copied Verbatim (Deterministic Code):
   - `order_id`, `dispatch_ts`, `delivery_ts`, `delivery_otp_confirmed`, `pod_document_id`,
     `delivery_geotag`, `redemption_ts`.
   - These fields are NEVER regenerated by the LLM. Regenerating identifiers via an LLM call
     introduces unacceptable hallucination risk; they are copied verbatim in Python code from
     the merchant evidence store via `build_contest_payload_from_evidence`.
3. Fact-Validation Hard-Block (validate_facts.py):
   - The LLM's `summary` draft is audited before submission. If any document ID, timestamp,
     courier name, or unverified OTP assertion is present in the summary that does not match
     the source record verbatim, the draft is rejected.
   - On rejection or missing credentials, the system logs granular failure reasons and safely
     falls back to the deterministic evidence-only payload.
========================================================================================
"""

